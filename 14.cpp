#include <stdio.h>             // Biblioteca para usar printf

int main()                    // Função principal
{
    int i;                    // Variável de controle

    for(i = 1; i <= 10; i++)  // Conta de 1 até 10
    {
        printf("%d\n", i);    // Exibe o número atual
    }

    return 0;                 // Finaliza o programa
}